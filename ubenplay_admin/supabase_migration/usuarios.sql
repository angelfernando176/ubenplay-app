-- ============================================================
-- Lingo — Tablas de gestión de usuarios (Fase 0)
-- Ejecutar en Supabase SQL Editor
-- ============================================================

-- 1. Usuarios (estudiantes registrados desde la APK)
CREATE TABLE IF NOT EXISTS public.usuarios (
  id_usuario BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre VARCHAR(100),
  apellido VARCHAR(100),
  correo VARCHAR(150) UNIQUE NOT NULL,
  rango_edad INTEGER DEFAULT 2,          -- 1<18, 2=18-35, 3=36-50, 4>50
  pais VARCHAR(100),
  correo_representante VARCHAR(150),     -- solo si menor de edad
  nivel_acceso INTEGER DEFAULT 1,        -- 1 Registrado, 2 Funcional, 3 Licenciamiento1, 4 Licenciamiento2
  estado INTEGER DEFAULT 0,              -- 0 inactivo, 1 activo
  lopdp INTEGER DEFAULT 0,               -- 0 no autorizado, 1 autorizado
  insistencias INTEGER DEFAULT 0,
  codigo_hash VARCHAR(255),              -- hash del código de 6 dígitos
  codigo_expiracion TIMESTAMPTZ,
  fecha_registro TIMESTAMPTZ DEFAULT now()
);

-- 2. Historial de cambios de nivel de acceso (código encriptado)
CREATE TABLE IF NOT EXISTS public.registro_usuarios (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  fecha_hora TIMESTAMPTZ DEFAULT now(),
  id_usuario BIGINT REFERENCES public.usuarios(id_usuario) ON DELETE CASCADE,
  codigo_enviado VARCHAR(255),           -- hash encriptado del código
  tipo_cambio VARCHAR(10)                -- '1->2', '2->3', '3->4'
);

-- 3. Eventos de ingreso/salida de la app (sync en background)
CREATE TABLE IF NOT EXISTS public.eventos_usuario (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_usuario BIGINT REFERENCES public.usuarios(id_usuario) ON DELETE CASCADE,
  tipo_evento VARCHAR(20),               -- login, logout, apertura
  fecha_hora TIMESTAMPTZ DEFAULT now(),
  dispositivo VARCHAR(100),
  sincronizado INTEGER DEFAULT 0         -- 0 pendiente, 1 sincronizado
);

-- ============================================================
-- RLS (mismo patrón permisivo que verbos/adjetivos)
-- ============================================================
ALTER TABLE public.usuarios ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.registro_usuarios ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.eventos_usuario ENABLE ROW LEVEL SECURITY;

CREATE POLICY "Allow all usuarios" ON public.usuarios FOR ALL USING (true) WITH CHECK (true);
CREATE POLICY "Allow all registro_usuarios" ON public.registro_usuarios FOR ALL USING (true) WITH CHECK (true);
CREATE POLICY "Allow all eventos_usuario" ON public.eventos_usuario FOR ALL USING (true) WITH CHECK (true);
